export function serializeEnvFile(values) {
  const lines = [
    "# Generated by npm run bootstrap for local mock development.",
    "# Keep this file local. Never copy Production credentials into it.",
  ];

  for (const [name, value] of Object.entries(values)) {
    lines.push(`${name}=${value}`);
  }

  return `${lines.join("\n")}\n`;
}

function looksLikePlaceholder(value) {
  const normalized = value.toLowerCase();
  return (
    normalized.startsWith("replace-with-") ||
    normalized.startsWith("your-") ||
    normalized.includes("example.com")
  );
}

function isValidUrl(value, { allowHttpLocalhost = false } = {}) {
  try {
    const url = new URL(value);
    if (url.protocol === "https:") {
      return true;
    }
    return (
      allowHttpLocalhost &&
      url.protocol === "http:" &&
      ["localhost", "127.0.0.1", "::1"].includes(url.hostname)
    );
  } catch {
    return false;
  }
}

export function validateEnvironment(environment) {
  const diagnostics = [];
  const nodeEnvironment = (environment.NODE_ENV || "development").trim();
  const isProduction = nodeEnvironment === "production";
  const requiredNames = isProduction
    ? PRODUCTION_REQUIRED_ENV
    : DEVELOPMENT_REQUIRED_ENV;

  for (const name of requiredNames) {
    if (!environment[name]?.trim()) {
      diagnostics.push(
        diagnostic(
          "FAIL",
          "environment_required",
          name,
          `${name} is missing or empty.`,
          isProduction
            ? "Configure the variable in the Production environment source of truth."
            : "Run npm run bootstrap or restore the reviewed local environment file.",
        ),
      );
    }
  }

  for (const name of Object.keys(environment)) {
    const canonicalName = [...KNOWN_ENV_NAMES].find(
      (known) => known.toLowerCase() === name.toLowerCase(),
    );
    if (canonicalName && canonicalName !== name) {
      diagnostics.push(
        diagnostic(
          "FAIL",
          "environment_name_case",
          name,
          `Environment variable casing must be ${canonicalName}.`,
          `Rename ${name} to ${canonicalName} in the environment source of truth.`,
        ),
      );
    }
  }

  if (
    isProduction &&
    (environment.NEXT_PUBLIC_DATA_SOURCE === "mock" ||
      environment.NEXT_PUBLIC_PARTNER_PORTAL_DATA_SOURCE === "mock")
  ) {
    diagnostics.push(
      diagnostic(
        "FAIL",
        "production_mock_forbidden",
        "NODE_ENV",
        "Production cannot use a mock data source.",
        "Set both public data sources to supabase before deployment.",
      ),
    );
  }

  for (const name of [
    "NEXT_PUBLIC_DATA_SOURCE",
    "NEXT_PUBLIC_PARTNER_PORTAL_DATA_SOURCE",
  ]) {
    const value = environment[name]?.trim();
    if (value && !["mock", "supabase"].includes(value)) {
      diagnostics.push(
        diagnostic(
          "FAIL",
          "environment_invalid_choice",
          name,
          `${name} has an unsupported value.`,
          "Use mock or supabase with the same spelling on every OS.",
        ),
      );
    }
  }

  for (const name of URL_ENV_NAMES) {
    const value = environment[name]?.trim();
    if (
      value &&
      !isValidUrl(value, {
        allowHttpLocalhost: !isProduction && name === "NEXT_PUBLIC_SITE_URL",
      })
    ) {
      diagnostics.push(
        diagnostic(
          "FAIL",
          "environment_invalid_url",
          name,
          `${name} is not a valid allowed URL.`,
          "Use HTTPS, except localhost may use HTTP during development.",
        ),
      );
    }
  }

  for (const name of SECRET_ENV_NAMES) {
    const value = environment[name]?.trim();
    if (value && value.length < 32) {
      diagnostics.push(
        diagnostic(
          "FAIL",
          "environment_secret_too_short",
          name,
          `${name} does not satisfy the minimum secret length.`,
          "Replace it with at least 32 characters. The current value was not printed.",
        ),
      );
    }
  }

  if (
    environment.SMTP_PORT?.trim() &&
    !/^\d{1,5}$/u.test(environment.SMTP_PORT.trim())
  ) {
    diagnostics.push(
      diagnostic(
        "FAIL",
        "environment_invalid_port",
        "SMTP_PORT",
        "SMTP_PORT must be a numeric TCP port.",
        "Use an integer between 1 and 65535.",
      ),
    );
  }

  if (
    environment.SMTP_SECURE?.trim() &&
    !["true", "false"].includes(environment.SMTP_SECURE.trim())
  ) {
    diagnostics.push(
      diagnostic(
        "FAIL",
        "environment_invalid_boolean",
        "SMTP_SECURE",
        "SMTP_SECURE must be true or false.",
        "Use a lowercase boolean literal.",
      ),
    );
  }

  if (isProduction) {
    for (const name of PRODUCTION_REQUIRED_ENV) {
      const value = environment[name]?.trim();
      if (value && looksLikePlaceholder(value)) {
        diagnostics.push(
          diagnostic(
            "FAIL",
            "environment_placeholder",
            name,
            `${name} still contains a placeholder value.`,
            "Replace it in the Production environment source of truth.",
          ),
        );
      }
    }
  }

  if (diagnostics.length === 0) {
    diagnostics.push(
      diagnostic(
        "PASS",
        "environment_valid",
        "Environment",
        `${isProduction ? "Production" : "Development"} environment contract is valid.`,
        "No action required.",
      ),
    );
  }

  return diagnostics;
}

export function resolveNpmCliPath(environment = process.env) {
  const npmExecPath = environment.npm_execpath?.trim();
  return npmExecPath || null;
}

export function runNodeCli(cliPath, args, options = {}) {
  if (!cliPath) {
    return {
      status: 1,
      error: new Error("npm_execpath is unavailable"),
      stdout: "",
      stderr: "",
    };
  }
  return spawnSync(process.execPath, [cliPath, ...args], {
    cwd: repositoryRoot,
    encoding: "utf8",
    ...options,
  });
}

export function findExecutableOnPath(command, environment = process.env) {
  const pathValue = environment.PATH;
  if (!pathValue) {
    return null;
  }

  const extensions =
    process.platform === "win32"
      ? (environment.PATHEXT || ".EXE;.CMD;.BAT;.COM").split(";")
      : [""];

  for (const directory of pathValue.split(delimiter).filter(Boolean)) {
    for (const extension of extensions) {
      const candidate = join(directory, `${command}${extension}`);
      try {
        accessSync(candidate, fsConstants.X_OK);
        return candidate;
      } catch {
        // Continue to the next PATH entry.
      }
    }
  }

  return null;
}

export function readCommandVersion(commandPath, args = ["--version"]) {
  if (!commandPath) {
    return null;
  }
  const result = spawnSync(commandPath, args, {
    cwd: repositoryRoot,
    encoding: "utf8",
  });
  if (result.status !== 0 || result.error) {
    return null;
  }
  return result.stdout.trim();
}

function readNpmVersion(environment) {
  const npmCliPath = resolveNpmCliPath(environment);
  if (!npmCliPath) {
    return null;
  }
  const result = runNodeCli(npmCliPath, ["--version"], {
    env: environment,
  });
  return result.status === 0 ? result.stdout.trim() : null;
}

function checkPortAvailable(port) {
  return new Promise((resolveCheck) => {
    const server = createServer();
    server.unref();
    server.once("error", () => resolveCheck(false));
    server.listen({ host: "127.0.0.1", port }, () => {
      server.close(() => resolveCheck(true));
    });
  });
}

export async function collectDoctorDiagnostics({
  root = repositoryRoot,
  environment = process.env,
  platform = process.platform,
  architecture = process.arch,
  checkPort = true,
} = {}) {
  const diagnostics = [];
  const platformInfo = classifyPlatform(platform, architecture);

  if (platformInfo.support === "unsupported") {
    diagnostics.push(
      diagnostic(
        "FAIL",
        "platform_unsupported",
        "Platform",
        `${platformInfo.label} is not a supported development platform.`,
        "Use Windows x64 or macOS arm64. Linux x64 is supported for CI only.",
      ),
    );
  } else {
    diagnostics.push(
      diagnostic(
        platformInfo.support === "official" ? "PASS" : "WARN",
        "platform_supported",
        "Platform",
        `${platformInfo.label} support level: ${platformInfo.support}.`,
        platformInfo.support === "official"
          ? "No action required."
          : "Use this platform for CI verification, not as the official local handoff target.",
      ),
    );
  }

  diagnostics.push(
    process.versions.node === REQUIRED_NODE_VERSION
      ? diagnostic(
          "PASS",
          "runtime_node",
          "Node.js",
          `Node.js ${REQUIRED_NODE_VERSION} is active.`,
          "No action required.",
        )
      : diagnostic(
          "FAIL",
          "runtime_node",
          "Node.js",
          `Node.js ${REQUIRED_NODE_VERSION} is required; ${process.versions.node} is active.`,
          `Activate the repository-pinned Node.js ${REQUIRED_NODE_VERSION} runtime and rerun npm run doctor.`,
        ),
  );

  const npmVersion = readNpmVersion(environment);
  diagnostics.push(
    npmVersion === REQUIRED_NPM_VERSION
      ? diagnostic(
          "PASS",
          "package_manager_npm",
          "npm",
          `npm ${REQUIRED_NPM_VERSION} is active.`,
          "No action required.",
        )
      : diagnostic(
          "FAIL",
          "package_manager_npm",
          "npm",
          `npm ${REQUIRED_NPM_VERSION} is required; ${npmVersion || "unavailable"} is active.`,
          `Activate npm ${REQUIRED_NPM_VERSION} through the pinned project runtime and rerun npm run doctor.`,
        ),
  );

  const gitPath = findExecutableOnPath("git", environment);
  const gitVersion = readCommandVersion(gitPath);
  diagnostics.push(
    gitVersion
      ? diagnostic(
          "PASS",
          "required_cli_git",
          "Git",
          "Git is available on PATH.",
          "No action required.",
        )
      : diagnostic(
          "FAIL",
          "required_cli_git",
          "Git",
          "Git is not available on PATH.",
          "Install Git, restart the terminal, and rerun npm run doctor.",
        ),
  );

  const dependencyMarker = join(root, "node_modules", "next", "package.json");
  diagnostics.push(
    existsSync(dependencyMarker)
      ? diagnostic(
          "PASS",
          "dependencies_installed",
          "Dependencies",
          "Project dependencies are installed.",
          "No action required.",
        )
      : diagnostic(
          "FAIL",
          "dependencies_installed",
          "Dependencies",
          "Project dependencies are missing or incomplete.",
          "Run npm run bootstrap.",
        ),
  );

  const projectEnvironment = loadProjectEnvironment({ root, environment });
  diagnostics.push(...validateEnvironment(projectEnvironment.values));

  const usesMock =
    projectEnvironment.values.NEXT_PUBLIC_DATA_SOURCE === "mock" &&
    projectEnvironment.values.NEXT_PUBLIC_PARTNER_PORTAL_DATA_SOURCE === "mock";
  diagnostics.push(
    usesMock
      ? diagnostic(
          "PASS",
          "cloud_authentication",
          "Cloud authentication",
          "The local mock profile does not require cloud credentials.",
          "No action required.",
        )
      : diagnostic(
          "WARN",
          "cloud_authentication",
          "Cloud authentication",
          "A cloud-backed profile is selected; provider login cannot be proven without a network mutation.",
          "Confirm the reviewed Supabase and Vercel credentials before cloud operations.",
        ),
  );

  const vercelProject = join(root, ".vercel", "project.json");
  diagnostics.push(
    existsSync(vercelProject)
      ? diagnostic(
          "PASS",
          "project_linking",
          "Project linking",
          "A local Vercel project link exists.",
          "No action required.",
        )
      : diagnostic(
          usesMock ? "PASS" : "WARN",
          "project_linking",
          "Project linking",
          usesMock
            ? "Project linking is not required for the local mock profile."
            : "A local Vercel project link is not present.",
          usesMock
            ? "No action required."
            : "Use the repository-scoped Vercel command only when deployment work requires it.",
        ),
  );

  diagnostics.push(
    diagnostic(
      "PASS",
      "container_runtime",
      "Container runtime",
      "The default development profile does not require a container runtime.",
      "No action required.",
    ),
    diagnostic(
      "PASS",
      "local_database",
      "Local database",
      "The default mock profile does not require a local database.",
      "No action required.",
    ),
  );

  if (checkPort) {
    const portAvailable = await checkPortAvailable(DEVELOPMENT_PORT);
    diagnostics.push(
      portAvailable
        ? diagnostic(
            "PASS",
            "development_port",
            `Port ${DEVELOPMENT_PORT}`,
            `Port ${DEVELOPMENT_PORT} is available.`,
            "No action required.",
          )
        : diagnostic(
            "WARN",
            "development_port",
            `Port ${DEVELOPMENT_PORT}`,
            `Port ${DEVELOPMENT_PORT} is already in use.`,
            "Stop the existing process or intentionally reuse the already running development server.",
          ),
    );
  }

  try {
    accessSync(root, fsConstants.R_OK | fsConstants.W_OK);
    diagnostics.push(
      diagnostic(
        "PASS",
        "filesystem_permission",
        "Filesystem",
        "The repository root is readable and writable.",
        "No action required.",
      ),
    );
  } catch {
    diagnostics.push(
      diagnostic(
        "FAIL",
        "filesystem_permission",
        "Filesystem",
        "The repository root is not both readable and writable.",
        "Move the clone to a developer-owned directory or correct its permissions.",
      ),
    );
  }

  const lockfilePath = join(root, "package-lock.json");
  let nativePackageAvailable = false;
  if (existsSync(lockfilePath)) {
    try {
      const lockfile = JSON.parse(readFileSync(lockfilePath, "utf8"));
      const packages = lockfile.packages || {};
      const nativePackage =
        platform === "win32" && architecture === "x64"
          ? "node_modules/@esbuild/win32-x64"
          : platform === "darwin" && architecture === "arm64"
            ? "node_modules/@esbuild/darwin-arm64"
            : platform === "linux" && architecture === "x64"
              ? "node_modules/@esbuild/linux-x64"
              : null;
      nativePackageAvailable = Boolean(nativePackage && packages[nativePackage]);
    } catch {
      nativePackageAvailable = false;
    }
  }
  diagnostics.push(
    nativePackageAvailable
      ? diagnostic(
          "PASS",
          "architecture_compatibility",
          "Native dependencies",
          "The lockfile includes the native package for this platform and architecture.",
          "No action required.",
        )
      : diagnostic(
          platformInfo.support === "unsupported" ? "WARN" : "FAIL",
          "architecture_compatibility",
          "Native dependencies",
          "The lockfile does not prove native dependency support for this platform and architecture.",
          "Use a supported platform or update the reviewed native dependency matrix.",
        ),
  );

  return diagnostics;
}

export function formatDiagnostic(item) {
  return `${item.level.padEnd(4)} ${item.subject}: ${item.message} Action: ${item.action}`;
}

export function printDiagnostics(diagnostics, stream = process.stdout) {
  for (const item of diagnostics) {
    stream.write(`${formatDiagnostic(item)}\n`);
  }
  const summary = { PASS: 0, WARN: 0, FAIL: 0 };
  for (const item of diagnostics) {
    summary[item.level] += 1;
  }
  stream.write(
    `Summary: PASS ${summary.PASS}, WARN ${summary.WARN}, FAIL ${summary.FAIL}\n`,
  );
  return summary;
}

export function directoryHasCaseInsensitiveEntry(directoryPath, expectedName) {
  try {
    const entries = readdirSync(directoryPath);
    return {
      exact: entries.includes(expectedName),
      folded: entries.find(
        (entry) => entry.toLowerCase() === expectedName.toLowerCase(),
      ),
    };
  } catch {
    return { exact: false, folded: undefined };
  }
}

export function nearestExistingParent(filePath) {
  let current = filePath;
  while (!existsSync(current)) {
    const parent = dirname(current);
    if (parent === current) {
      return null;
    }
    current = parent;
  }
  return current;
}
