function diagnostic(level, code, subject, message, action) {
  return { level, code, subject, message, action };
}

export function classifyPlatform(platform, architecture) {
  const known = PLATFORM_MATRIX.get(`${platform}-${architecture}`);
  if (known) {
    return { ...known };
  }

  return {
    key: `${platform}-${architecture}`,
    label: `${platform} ${architecture}`,
    support: "unsupported",
  };
}

export function parseEnvFile(source) {
  const parsed = {};

  for (const rawLine of source.replace(/^\uFEFF/u, "").split(/\r?\n/u)) {
    const line = rawLine.trim();
    if (!line || line.startsWith("#")) {
      continue;
    }

    const match = line.match(/^([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(.*)$/u);
    if (!match) {
      continue;
    }

    let value = match[2].trim();
    if (
      value.length >= 2 &&
      ((value.startsWith('"') && value.endsWith('"')) ||
        (value.startsWith("'") && value.endsWith("'")))
    ) {
      value = value.slice(1, -1);
    }
    parsed[match[1]] = value;
  }

  return parsed;
}

export function loadProjectEnvironment({ root = repositoryRoot, environment = process.env } = {}) {
  const loaded = {};
  const loadedFiles = [];

  for (const relativePath of ENV_FILES) {
    const filePath = join(root, relativePath);
    if (!existsSync(filePath)) {
      continue;
    }
    Object.assign(loaded, parseEnvFile(readFileSync(filePath, "utf8")));
    loadedFiles.push(relativePath);
  }

  return {
    values: { ...loaded, ...environment },
    loadedFiles,
  };
}

